"""Generate the example report in docs/example/ from SIMULATED data.

This shows what the analysis output looks like. None of it is a measurement:
the offsets, jitter and wander below were picked by hand for the demo, and the
analysis simply recovers them. Real results come from logs recorded on boards.

    python host/examples/make_demo.py
"""

from __future__ import annotations

import shutil
import tempfile
from pathlib import Path

from stm32timing import analysis, parse, report
from stm32timing.synth import synth_lines

OUT = Path(__file__).resolve().parents[2] / "docs" / "example"
BANNER = "SIMULATED"

# name: (title, generator settings) - values chosen by hand for illustration
SCENARIOS = {
    "e1_loopback": (
        "E1 loopback (simulated)",
        dict(n=120_000, sync=True, uid="DE300001", target="F411RE", lat_ticks=(25, 31), seed=11),
    ),
    "e3_board_a": (
        "E3 board A vs reference (simulated)",
        dict(n=300_000, ppm=11.8, jitter_ns=6.0, wander_ppm=0.002, uid="DE300001", target="F411RE", seed=21),
    ),
    "e3_board_b": (
        "E3 board B vs reference (simulated)",
        dict(n=300_000, ppm=-4.3, jitter_ns=6.0, wander_ppm=0.002, uid="DE300002", target="F446RE", lat_ticks=(20, 26), seed=22),
    ),
    "e5_board_b_hsi": (
        "E5 board B on HSI vs reference (simulated)",
        dict(n=300_000, ppm=2700.0, jitter_ns=6.0, wander_ppm=0.4, uid="DE300002", target="F446RE", clk="HSI", lat_ticks=(20, 26), seed=23),
    ),
}


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    report.set_watermark(BANNER)
    results = {}
    with tempfile.TemporaryDirectory() as tmp:
        for name, (title, kw) in SCENARIOS.items():
            log = Path(tmp) / f"{name}.log"
            log.write_text("\n".join(synth_lines(**kw)))
            r = analysis.analyze(parse.load(log), 1000.0)
            r.source = f"simulated ({name}, generated by host/examples/make_demo.py)"
            report.write_report(r, OUT / name, title)
            results[name] = r
    comp = analysis.compare(results["e3_board_a"], results["e3_board_b"])
    report.write_comparison(comp, OUT / "e3_compare")

    sections = [
        "# Example output (simulated data, not a measurement)",
        "",
        "> **Everything in this folder comes from generated data.** The offsets, jitter and wander were",
        "> chosen by hand in `host/examples/make_demo.py` to show what the analysis output looks like.",
        "> These are not measured values and are not typical values for any board.",
        "",
        "Regenerate with `python host/examples/make_demo.py`.",
        "",
    ]
    for name in SCENARIOS:
        sections.append(f"- [{SCENARIOS[name][0]}]({name}/results.md)")
    sections += ["- [E3 comparison of board A and B (simulated)](e3_compare/comparison.md)", ""]
    (OUT / "README.md").write_text("\n".join(sections))
    for md in OUT.rglob("*.md"):
        if md.name != "README.md":
            text = md.read_text()
            md.write_text(
                "> **Simulated data, not a measurement.** See [the example README]"
                f"({'../' * (len(md.relative_to(OUT).parts) - 1)}README.md).\n\n" + text
            )
    print(f"written {OUT}")


if __name__ == "__main__":
    main()
